"""Check local links and preserve the pinned scientific source before publishing."""

from hashlib import sha256
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PAPER_SHA256 = "3c8de5dc6bad53a043f7b6181603cf5af223979c92cfc5eb486f1fa7842a0731"


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.refs = []
        self.ids = set()

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get("id"):
            self.ids.add(attrs["id"])
        for key in ("href", "src"):
            if attrs.get(key):
                self.refs.append(attrs[key])


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for key, item in value.items():
            yield key
            yield from strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from strings(item)


def validate(root=ROOT):
    root = root.resolve()
    errors = []
    paper = root / "sources/SONIC_2025_bioRxiv_v1.pdf"
    if not paper.exists() or sha256(paper.read_bytes()).hexdigest() != PAPER_SHA256:
        errors.append("Pinned SONIC v1 PDF is missing or its bytes changed.")
    required = ["web/index.html", "web/styles.css", "web/app.js", "web/model.js",
                "web/parts.css", "web/parts.js", "web/parts-data.js", "web/assets/parts/sources.json",
                "web/compare.js", "web/compare.css"]
    for name in required:
        if not (root / name).is_file():
            errors.append(f"Missing application file: {name}")

    refs = []
    for path in (root / "web").glob("*.html"):
        parser = Links()
        parser.feed(path.read_text(encoding="utf-8"))
        refs.extend((path, ref) for ref in parser.refs)
        for ref in parser.refs:
            if ref.startswith("#") and ref[1:] not in parser.ids:
                errors.append(f"Missing HTML anchor in {path.name}: {ref}")

    markdown = list(root.glob("*.md"))
    for directory in ("docs", "sources", "output", "scripts"):
        markdown.extend((root / directory).rglob("*.md"))
    for path in markdown:
        for ref in re.findall(r"\]\(([^\s)]+)\)", path.read_text(encoding="utf-8")):
            refs.append((path, ref))

    # These links are generated by JavaScript and are absent from HTML attributes.
    data_file = root / "web/parts-data.js"
    try:
        data = json.loads(data_file.read_text().split("=", 1)[1].strip().removesuffix(";"))
        refs.extend((data_file, value) for value in strings(data)
                    if value.startswith(("../", "./", "assets/")))
    except (OSError, ValueError, IndexError) as exc:
        errors.append(f"Cannot read dynamic parts links: {exc}")

    for path, ref in refs:
        parts = urlsplit(ref)
        if parts.scheme or parts.netloc or not parts.path:
            continue
        if parts.path.startswith("/"):
            errors.append(f"Nonportable absolute link in {path.name}: {ref}")
            continue
        target = (path.parent / unquote(parts.path)).resolve()
        if not target.is_relative_to(root) or not target.exists():
            errors.append(f"Broken local link in {path.relative_to(root)}: {ref}")

    # Dated evidence retains original locations; resolve those through the move map.
    map_file = root / "docs/organization/2026-10-16_path_moves.json"
    aliases = {}
    try:
        for move in json.loads(map_file.read_text())["moves"]:
            aliases[move["from"]] = move["to"]
            if move.get("observed_user_source"):
                aliases[move["observed_user_source"]] = move["to"]
    except (OSError, ValueError, KeyError) as exc:
        errors.append(f"Cannot read relocation map: {exc}")
    records = list((root / "sources").glob("*.json"))
    records.extend((root / "docs/verification").glob("*.json"))
    records.append(map_file)
    checked_paths = 0
    for path in records:
        try:
            record = json.loads(path.read_text())
        except (OSError, ValueError) as exc:
            errors.append(f"Invalid record {path.relative_to(root)}: {exc}")
            continue
        for value in strings(record):
            if not value.startswith(("sources/", "output/", "outputs/", "docs/", "scripts/", "web/")):
                continue
            if Path(value).suffix.lower() not in {".pdf", ".tex", ".md", ".json", ".py", ".png", ".jpg", ".xlsx", ".docx"}:
                continue
            decoded = unquote(value)
            target = (root / aliases.get(decoded, decoded)).resolve()
            checked_paths += 1
            if not target.is_relative_to(root) or not target.is_file():
                errors.append(f"Broken evidence path in {path.relative_to(root)}: {value}")

    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    print(f"Validated {len(refs)} links, {checked_paths} evidence paths and unchanged SONIC v1 PDF in {root.name}/.")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help="Repository or generated site root")
    sys.exit(validate(parser.parse_args().root))
